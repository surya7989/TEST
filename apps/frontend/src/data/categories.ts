export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES.find(c => c.slug === slug);
}

export function getSubcategories(parentSlug: string): Category[] {
  return CATEGORIES.filter(c => c.parentSlug === parentSlug);
}

export const CLINICAL_PRIMARY_CATEGORIES: Category[] = CATEGORIES.filter(c => c.depth === 1 || !c.parentSlug);

export function getCategoryBreadcrumbs(slug: string): Category[] {
  const crumbs: Category[] = [];
  let current = getCategoryBySlug(slug);
  while (current) {
    crumbs.unshift(current);
    current = current.parentSlug ? getCategoryBySlug(current.parentSlug) : undefined;
  }
  return crumbs;
}

